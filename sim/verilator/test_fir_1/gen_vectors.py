#!/usr/bin/env python3
"""Generate test_fir_1 stimulus (C header for CS20 firmware) and the expected
FIR output, using the bit-exact model in libs/q-engine/hdl/fir/model.

Outputs:
  override/fpgas/cs/cs20/c/src/fir_vectors.h  words, packet table
  expected.hex                                expected CS20 output words
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../../../libs/q-engine/hdl/fir/model"))
import fir_model as fm  # noqa: E402

SEED = 0xF1F00001
NTAPS = 16

# firmware op codes (must match main.c)
OP_COEF, OP_DATA, OP_RESET, OP_RAW = 1, 2, 3, 4


def main():
    rng = random.Random(SEED)
    coef_a = [fm.rand_word(rng, 0x1FFF) for _ in range(NTAPS)]
    coef_b = [fm.rand_word(rng, 0x7FFF) for _ in range(NTAPS)]  # saturates

    def data(n):
        return ("data", [fm.rand_word(rng) for _ in range(n)])

    rw = lambda: fm.rand_word(rng)  # noqa: E731
    ops = [
        ("coef", coef_a, 15),
        data(100), data(37), data(1),          # one stream over 3 DMAs
        ("coef", coef_b, 17),                  # history kept, new shift, some saturation
        data(150),
        ("reset",),
        data(50),
        ("raw", [0xDEADBEEF, rw(), rw()]),                       # ERR_HDR
        ("raw", [fm.header(fm.OP_LOAD_COEFFS, 3)] + [rw() for _ in range(5)]),  # ERR_COEF_LEN
        ("raw", [fm.header(fm.OP_DATA, reserved=0x80), rw()]),   # ERR_HDR (reserved)
        data(64),                              # history/coefs unaffected
        ("raw", [fm.header(fm.OP_RESET), rw(), rw()]),           # ERR_RST_LEN, reset applied
        data(33),
        ("coef", coef_a, 15),
        data(40),
    ]

    model = fm.FirModel(NTAPS)
    words = []      # input pool, copied to VMEM by the firmware
    table = []      # (op, offset, n, shift, out_offset)
    expected = []
    out_off = 0
    for op in ops:
        kind = op[0]
        if kind == "coef":
            _, c, shift = op
            table.append((OP_COEF, len(words), NTAPS, shift, 0))
            words += c
            beats = fm.pkt_coef(c, shift)
        elif kind == "data":
            s = op[1]
            table.append((OP_DATA, len(words), len(s), 0, out_off))
            words += s
            out_off += len(s)
            beats = fm.pkt_data(s)
        elif kind == "reset":
            table.append((OP_RESET, 0, 0, 0, 0))
            beats = fm.pkt_reset()
        else:
            r = op[1]
            table.append((OP_RAW, len(words), len(r), 0, 0))
            words += r
            beats = fm.pkt_raw(r)
        outs = model.run(beats)
        if kind == "data":
            assert len(outs) == len(op[1]) and outs[-1][1] == 1
        else:
            assert not outs, kind
        expected += [w for w, _ in outs]

    assert model.err == fm.ERR_HDR | fm.ERR_COEF_LEN | fm.ERR_RST_LEN
    assert len(expected) == out_off
    sat_hits = sum(1 for w in expected
                   for v in fm.unpack(w) if v in (0x7FFF, -0x8000))
    assert sat_hits > 0, "coefficient set B must exercise saturation"

    hdr = os.path.join(HERE, "override/fpgas/cs/cs20/c/src/fir_vectors.h")
    with open(hdr, "w") as f:
        f.write("// Generated by gen_vectors.py (seed 0x%08X). Do not edit.\n" % SEED)
        f.write("#ifndef __FIR_VECTORS_H__\n#define __FIR_VECTORS_H__\n\n")
        f.write("#define FIRV_OP_COEF  (%d)\n#define FIRV_OP_DATA  (%d)\n"
                "#define FIRV_OP_RESET (%d)\n#define FIRV_OP_RAW   (%d)\n\n"
                % (OP_COEF, OP_DATA, OP_RESET, OP_RAW))
        f.write("#define FIRV_WORDS   (%d)\n" % len(words))
        f.write("#define FIRV_OPS     (%d)\n" % len(table))
        f.write("#define FIRV_OUTPUTS (%d)\n\n" % out_off)
        f.write("typedef struct { unsigned short op, offset, n, shift, out; } firv_op_t;\n\n")
        f.write("static firv_op_t firv_ops[FIRV_OPS] = {\n")
        for t in table:
            f.write("    {%d, %d, %d, %d, %d},\n" % t)
        f.write("};\n\n")
        f.write("static unsigned int firv_words[FIRV_WORDS] = {\n")
        for i in range(0, len(words), 6):
            f.write("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",\n")
        f.write("};\n\n#endif\n")

    with open(os.path.join(HERE, "expected.hex"), "w") as f:
        for w in expected:
            f.write("%08x\n" % w)
    print("gen_vectors: %d ops, %d input words, %d expected outputs, %d saturated lanes"
          % (len(table), len(words), len(expected), sat_hits))


if __name__ == "__main__":
    main()
