#!/usr/bin/env node
'use strict';

const templates = require('../templates.js');
const datapathTemplates = require('../datapath-templates');
const path = require('path');
const fs = require('fs-extra');
const fhyper = require('reqack/lib/fhyper');
const fhyperDot = require('reqack/lib/fhyper-dot');
const fhyperV = require('reqack/lib/fhyper-verilog');
const k15_op = require('../lib/k15_op');
const piston = require('../lib/piston');
const macros = require('../lib/macros');
const macrosDatapath = require('../../../datapath/lib/datapath-macros');
const imgDatapath = require('../../../datapath/lib/img-datapath');
const fftDatapath = require('../../../datapath/lib/datapath');
const allMacros = Object.assign({}, macros, macrosDatapath, imgDatapath.macros);

const constants = require('../lib/constants');
//console.log(constants);

const props = {
    iAddrWidth: 16,
    oAddrWidth: 11+constants.divlog2,
    inputs: 4,
    outputs: 32,
    dataWidth: 32,
    dmaOutStages: 3,
    law: {
        inmux: [1, 5, 7],
	inmuxReal: [1, 13, 15],
        oumux: [8, 9, 13, 14, 15],
        selin: 4,
        selou: 4,
        perin: 5-constants.divlog2,
        perou: 5-constants.divlog2,
        baddr: 11+constants.divlog2,
	saddr: 16,
        k15: 32
    },
    
    slices: 32/constants.div,
    log2slices: Math.log2(32/constants.div),

    funnel: {
        minWidth: 4, // 4x18-bit outputs
        maxWidth: 16, // 16x18-bit outputs
        steps: 3 // 64:4 64:8 64:16
    },
    cfg: [
        8, 8, 8, 8, 8, 8, 8, 8, // bs
        8, 8, 8 // funnel funnel defunnel
    ]
};

const fineGrain = {
    'inmux_dat.v':[[4,1]],
    'oumux_dat.v':[[2,5]],
    'iperm_dat.v':[[2,1]],
    'operm_dat.v':[[2,1]],
    'kap_ctrl_dat.v':[[1,5]],
    'rdp_systolic_dat.v':[[5,2]],
    'vector_dat.v':[[props.slices+1,2]],
    'vmem_dat.v':[[6,5]],
    'ka_decode_dat.v':[[1,3]],
    'p_decode_dat.v':[[1,2]],

    'inmux_ctrl.v':[[4,1]],
    'oumux_ctrl.v':[[2,5]],
    'iperm_ctrl.v':[[2,1]],
    'operm_ctrl.v':[[2,1]],
    'kap_ctrl_ctrl.v':[[1,5]],
    'rdp_systolic_ctrl.v':[[5,2]],
    'vector_ctrl.v':[[props.slices+1,2]],
    'vmem_ctrl.v':[[6,5]],
    'ka_decode_ctrl.v':[[1,3]],
    'p_decode_ctrl.v':[[1,2]],

    'bs_dat.v': [[2, 1]],
    'round_sat_dat.v' : [[1,1]],

    'funnel_dat.v':    [[2, 1], [2, 2], [2, 4]],
    'funnel_ctrl.v':   [[2, 1], [2, 2], [2, 4]],

    'defunnel_dat.v':  [[2, 1], [3, 1], [5, 1]],
    'defunnel_ctrl.v': [[2, 1], [3, 1], [5, 1]]
}

const allTemplates = Object.assign({},templates,datapathTemplates);
const withoutTrailingWhitespace = content => content.replace(/[ \t]+$/gm, '');

Object.keys(allTemplates).forEach(fileName => {
    const extName = path.extname(fileName);
    const baseName = path.basename(fileName, extName);
    (fineGrain[fileName] || [[]]).forEach(subUnit => {
        const body = allTemplates[fileName](Object.assign({local: subUnit}, props));
        const outPath = path.resolve(process.cwd(), 'hdl', baseName + subUnit.map(e => '_' + e).join('') + extName);
        fs.outputFile(
            outPath,
            withoutTrailingWhitespace(body),
            'utf-8',
            function (err) { if (err) { throw err; } }
        );
    });
});

// piston.v and piston_dp_{fft,img}.v are generated by SpinalHDL (libs/spinal,
// qengine.PistonVerilog). The reqack netlists are kept in build/ref/ as the
// equivalence references: piston.v (FFT datapath) and piston_img.v.
const variants = [
    {name: 'piston', dpGen: undefined},        // FFT datapath (default)
    {name: 'piston_img', dpGen: imgDatapath}  // image kernel datapath
];
// graph dump for libs/spinal/names/map.py; dp is the [n0,n1) node and
// [e0,e1) edge range created by the datapath generator
const graphJson = (g, dp) => {
    const idx = n => g.nodes.indexOf(n);
    return JSON.stringify({
        nodes: g.nodes.map(n => ({label: n.label === undefined ? null : n.label,
            from: n.from.map(e => g.edges.indexOf(e)), to: n.to.map(e => g.edges.indexOf(e))})),
        edges: g.edges.map(e => ({
            src: idx(e.source.node), idx: e.source.index, taillabel: e.taillabel,
            targets: e.targets.map(t => [idx(t.node), t.headlabel])
        })),
        dp
    }) + '\n';
};
variants.forEach(v => {
    const g = fhyper('piston');
    const dpGen = v.dpGen || fftDatapath;
    let dp;
    piston(g, gg => targets => {
        const n0 = g.nodes.length, e0 = g.edges.length;
        const r = dpGen(gg)(targets);
        dp = {n0, n1: g.nodes.length, e0, e1: g.edges.length};
        return r;
    })();
    fs.outputFile('build/ref/' + v.name + '.dot', fhyperDot(g), () => {});
    fs.outputFile('build/ref/' + v.name + '.v', withoutTrailingWhitespace(fhyperV(g, allMacros)), () => {});
    fs.outputFile('build/ref/' + v.name + '.json', graphJson(g, dp), () => {});
});
// UNODE_NAME: instance name of the vmem data module in the Spinal piston.v
const vmemH = '#define UNODE_NAME vmem\n' + '#define VMEM_INPUTS ' + fineGrain['vmem_dat.v'][0][0] + '\n' + '#define VMEM_OUTPUTS ' + fineGrain['vmem_dat.v'][0][1] + '\n';

// Equivalence references for SpinalHDL piston_dp_{fft,img}.v: the datapath
// graph alone, with k8/k9/k14 targets and the k1 initiator as ports.
[['fft', fftDatapath], ['img', imgDatapath]].forEach(([name, dpGen]) => {
    const g = fhyper('piston_dp');
    const w = {width: 32*32/constants.div, capacity: 0};
    const dpTargets = {k8: g('k8')(w), k9: g('k9')(w), k14: g('k14')(w)};
    dpGen(g)(dpTargets).k1(g('k1'));
    fs.outputFile('build/ref/piston_dp_' + name + '.v', withoutTrailingWhitespace(fhyperV(g, allMacros)), () => {});
    fs.outputFile('build/ref/piston_dp_' + name + '.json', graphJson(g, null), () => {});
});
fs.outputFile('c/vmem_node.h',vmemH, () => {});

// k15_op.v is generated by SpinalHDL (libs/spinal, qengine.K15OpVerilog);
// the reqack netlist is kept in build/ref/ as the equivalence reference
// (libs/spinal/equiv, make -C libs/q-engine/piston equiv).
const k15 = fhyper('k15_op');
k15_op(k15)();
fs.outputFile('build/ref/k15_op.dot', fhyperDot(k15), () => {
    fs.outputFile('build/ref/k15_op.v', withoutTrailingWhitespace(fhyperV(k15, allMacros)), () => {});
});
