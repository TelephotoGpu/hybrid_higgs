#!/usr/bin/env python3
"""Bit-exact model of the Q-engine Efficient Golay Correlator (``golay_corr``).

This is the single source of truth for the phase-2 contract in
doc/add-fir/PLAN.md.

Word format (same as the FIR): I (real) in [15:0], Q (imag) in [31:16],
signed 16-bit.  Stage k = 1..M has delay D_k = 2**P(k) and seed w_k in
{+1, -1, +j, -j} (codes 0..3).  Multiplying by a seed is a swap/negate, so
the datapath needs no multipliers.

    ra_0 = rb_0 = x
    ra_k[n] = conj(w_k) * ra_{k-1}[n - D_k] + rb_{k-1}[n]
    rb_k[n] = conj(w_k) * ra_{k-1}[n - D_k] - rb_{k-1}[n]

    mode 0: C = Ra[n-L] + Rb[n]    mode 1: Ra    mode 2: Rb
    out  = sat16((v + round) >>> shift)   (per component, same as the FIR)

Delays count samples (valid beats), not clock cycles.
"""

MAGIC = 0xC0A7
OP_DATA = 1
OP_LOAD_CFG = 2
OP_RESET = 3

ERR_HDR = 1
ERR_CFG_LEN = 2
ERR_RST_LEN = 4
ERR_CFG = 8

W_P1, W_M1, W_PJ, W_MJ = 0, 1, 2, 3
W_VALUE = {W_P1: 1, W_M1: -1, W_PJ: 1j, W_MJ: -1j}


def s16(v):
    v &= 0xFFFF
    return v - 0x10000 if v & 0x8000 else v


def pack(i, q):
    return ((q & 0xFFFF) << 16) | (i & 0xFFFF)


def unpack(w):
    return s16(w), s16(w >> 16)


def sat(v, bits=16):
    hi = (1 << (bits - 1)) - 1
    lo = -(1 << (bits - 1))
    return hi if v > hi else lo if v < lo else v


def round_shift(acc, shift):
    if shift:
        acc += 1 << (shift - 1)
    return acc >> shift


def header(op, shift=0, mode=0, magic=MAGIC, reserved=0):
    return (((magic & 0xFFFF) << 16) | ((shift & 0x1F) << 8) | ((mode & 3) << 6)
            | (op & 0xF) | reserved) & 0xFFFFFFFF


def cfg_word(p, w, reserved=0):
    return ((w & 3) << 4) | (p & 0xF) | reserved


def header_valid(w):
    """Magic, reserved bits and op. A non-zero mode is only legal on LOAD_CFG."""
    op = w & 0xF
    return ((w >> 16) == MAGIC and (w & 0xE030) == 0
            and op in (OP_DATA, OP_LOAD_CFG, OP_RESET)
            and (op == OP_LOAD_CFG or (w >> 6) & 3 == 0))


def cfg_word_valid(word, m):
    return (word & ~0x3F) == 0 and (word & 0xF) < m


def mul_conj_seed(v, code):
    """conj(w) * v for integer (re, im); conj(+j) = -j, conj(-j) = +j."""
    r, i = v
    if code == W_P1:
        return (r, i)
    if code == W_M1:
        return (-r, -i)
    if code == W_PJ:   # -j * (r + ji) = i - jr
        return (i, -r)
    return (-i, r)     # +j * (r + ji) = -i + jr


def default_cfg(m):
    return list(range(m)), [W_P1] * m


def golay_pair(p, w):
    """Sequence pair (a, b) generated by the stage config, as complex lists.

    The length is 1 + sum(D_k); for a permutation of 0..M-1 that is L = 2**M
    and (a, b) is a Golay complementary pair.  For any config the correlator
    computes Ra[n] = sum_i conj(a[i]) x[n - len(a) + 1 + i] (likewise Rb).
    """
    m = len(p)
    ln = 1 + sum(1 << q for q in p)
    a = [0j] * ln
    b = [0j] * ln
    a[0] = b[0] = 1
    for k in range(m):
        d = 1 << p[k]
        wk = W_VALUE[w[k]]
        bd = [b[n - d] if n >= d else 0 for n in range(ln)]
        a, b = [wk * a[n] + bd[n] for n in range(ln)], [wk * a[n] - bd[n] for n in range(ln)]
    return a, b


def is_permutation(p):
    return sorted(p) == list(range(len(p)))


class GolayModel:
    def __init__(self, m=7):
        self.m = m
        self.L = 1 << m
        self.depth = 1 << (m - 1)
        self.p, self.w = default_cfg(m)
        self.shift = m
        self.mode = 0
        self.err = 0
        self._state = "HDR"
        self._shadow = []
        self._shadow_bad = False
        self._shadow_shift = 0
        self._shadow_mode = 0
        self.reset_history()

    def reset_history(self):
        # hist[k][d-1] = ra_k[n-d], the delayed-branch input of stage k+1
        self.hist = [[(0, 0)] * self.depth for _ in range(self.m)]
        self.rhist = [(0, 0)] * self.L

    def correlate(self, x):
        """Advance one sample; return (Ra, Rb, C) as integer (re, im) tuples."""
        ra = rb = x
        for k in range(self.m):
            d = 1 << self.p[k]
            h = self.hist[k]
            dly = mul_conj_seed(h[d - 1], self.w[k])
            self.hist[k] = [ra] + h[:-1]
            ra, rb = ((dly[0] + rb[0], dly[1] + rb[1]),
                      (dly[0] - rb[0], dly[1] - rb[1]))
        ra_old = self.rhist[self.L - 1]
        self.rhist = [ra] + self.rhist[:-1]
        c = (ra_old[0] + rb[0], ra_old[1] + rb[1])
        return ra, rb, c

    def sample(self, word):
        ra, rb, c = self.correlate(unpack(word))
        v = (c, ra, rb)[self.mode]
        return pack(sat(round_shift(v[0], self.shift)), sat(round_shift(v[1], self.shift)))

    def push(self, word, last):
        """Consume one input beat. Returns an output beat (word, last) or None."""
        word &= 0xFFFFFFFF
        last = 1 if last else 0
        st = self._state
        if st == "HDR":
            if not header_valid(word):
                self.err |= ERR_HDR
                self._state = "HDR" if last else "DRAIN"
                return None
            op = word & 0xF
            if op == OP_DATA:
                self._state = "HDR" if last else "DATA"
            elif op == OP_LOAD_CFG:
                mode = (word >> 6) & 3
                if mode == 3:
                    self.err |= ERR_CFG
                    self._state = "HDR" if last else "DRAIN"
                elif last:
                    self.err |= ERR_CFG_LEN
                    self._state = "HDR"
                else:
                    self._shadow = []
                    self._shadow_bad = False
                    self._shadow_shift = (word >> 8) & 0x1F
                    self._shadow_mode = mode
                    self._state = "CFG"
            else:  # RESET
                self.reset_history()
                self._state = "HDR"
                if not last:
                    self.err |= ERR_RST_LEN
                    self._state = "DRAIN"
            return None
        if st == "DATA":
            if last:
                self._state = "HDR"
            return (self.sample(word), last)
        if st == "CFG":
            if not cfg_word_valid(word, self.m):
                self._shadow_bad = True
            self._shadow.append(word)
            if len(self._shadow) == self.m:
                if self._shadow_bad:
                    self.err |= ERR_CFG
                if not last:
                    self.err |= ERR_CFG_LEN
                    self._state = "DRAIN"
                    return None
                if not self._shadow_bad:
                    self.p = [v & 0xF for v in self._shadow]
                    self.w = [(v >> 4) & 3 for v in self._shadow]
                    self.shift = self._shadow_shift
                    self.mode = self._shadow_mode
                self._state = "HDR"
            elif last:
                self.err |= ERR_CFG_LEN
                if self._shadow_bad:
                    self.err |= ERR_CFG
                self._state = "HDR"
            return None
        if st == "DRAIN":
            if last:
                self._state = "HDR"
            return None
        raise AssertionError(st)

    def run(self, beats):
        out = []
        for w, l in beats:
            r = self.push(w, l)
            if r is not None:
                out.append(r)
        return out


# ---------------------------------------------------------------- packets
def _frame(hdr, payload):
    if not payload:
        return [(hdr, 1)]
    return [(hdr, 0)] + [(w, 1 if i == len(payload) - 1 else 0) for i, w in enumerate(payload)]


def pkt_data(samples):
    return _frame(header(OP_DATA), list(samples))


def pkt_cfg(p, w, shift, mode=0):
    return _frame(header(OP_LOAD_CFG, shift, mode), [cfg_word(pk, wk) for pk, wk in zip(p, w)])


def pkt_reset(extra=()):
    return _frame(header(OP_RESET), list(extra))


def pkt_raw(words):
    return [(w, 1 if i == len(words) - 1 else 0) for i, w in enumerate(words)]


def rand_word(rng, amp=0x7FFF):
    return pack(rng.randint(-amp - 1, amp), rng.randint(-amp - 1, amp))


def rand_cfg(rng, m, perm=True):
    if perm:
        p = list(range(m))
        rng.shuffle(p)
    else:
        p = [rng.randrange(m) for _ in range(m)]
    return p, [rng.randrange(4) for _ in range(m)]


def seq_words(seq, amp):
    """Map a sequence of +-1/+-j values to packed samples of amplitude amp."""
    return [pack(int(round(v.real * amp)), int(round(v.imag * amp))) for v in seq]


# ---------------------------------------------------------------- self test
def _selftest():
    import random

    rng = random.Random(7)
    for m in (1, 2, 3, 5, 7):
        L = 1 << m
        for trial in range(6):
            p, w = rand_cfg(rng, m, perm=(trial % 2 == 0))
            a, b = golay_pair(p, w)
            if is_permutation(p):
                assert all(v in (1, -1, 1j, -1j) for v in a + b)
                # complementary: aperiodic autocorrelations sum to 2L delta
                for s in range(1, L):
                    acc = sum(a[i + s] * a[i].conjugate() + b[i + s] * b[i].conjugate()
                              for i in range(L - s))
                    assert abs(acc) < 1e-9, (m, p, w, s, acc)
            # structural model == brute-force matched filter, any config
            g = GolayModel(m)
            g.p, g.w = p, w
            S = len(a)
            x = [(rng.randint(-0x8000, 0x7FFF), rng.randint(-0x8000, 0x7FFF))
                 for _ in range(3 * L + 5)]
            xc = [complex(*v) for v in x]
            ra_hist = []
            for n, v in enumerate(x):
                ra, rb, c = g.correlate(v)
                ref_a = sum(a[i].conjugate() * xc[n - S + 1 + i]
                            for i in range(S) if n - S + 1 + i >= 0)
                ref_b = sum(b[i].conjugate() * xc[n - S + 1 + i]
                            for i in range(S) if n - S + 1 + i >= 0)
                assert complex(*ra) == ref_a and complex(*rb) == ref_b, (m, p, w, n)
                ra_hist.append(ra)
                old = ra_hist[n - L] if n >= L else (0, 0)
                assert c == (old[0] + rb[0], old[1] + rb[1])
                bits = m + 17      # Ra/Rb width: 17 + M (|v| <= 2**(15+M))
                for comp in ra + rb:
                    assert -(1 << (bits - 1)) <= comp < (1 << (bits - 1))

    # |Ra|,|Rb| <= 2**(15+M) and +2**(15+M) is reachable, so 17+M bits are
    # needed: M=1, w=-1 gives b = [-1, -1] and x = -32768 makes Rb = +65536
    g = GolayModel(1)
    g.w = [W_M1]
    assert golay_pair(g.p, g.w)[1] == [-1, -1]
    g.correlate((-0x8000, 0))
    assert g.correlate((-0x8000, 0))[1] == (1 << 16, 0)

    # mode 0 peaks at 2L*amp at the last sample of b when a||b is sent
    m = 7
    L = 1 << m
    p, w = rand_cfg(random.Random(3), m)
    a, b = golay_pair(p, w)
    g = GolayModel(m)
    assert g.run(pkt_cfg(p, w, 0, 0)) == [] and g.err == 0
    amp = 100
    y = [unpack(o[0]) for o in g.run(pkt_data([0] * 10 + seq_words(a + b, amp) + [0] * 40))]
    peak = max(range(len(y)), key=lambda n: abs(complex(*y[n])))
    assert peak == 10 + 2 * L - 1 and y[peak] == (2 * L * amp, 0), (peak, y[peak])

    # defaults; rounding and saturation
    g = GolayModel(7)
    assert g.p == list(range(7)) and g.w == [0] * 7 and g.shift == 7 and g.mode == 0
    o = g.run(pkt_data([pack(0x7FFF, -0x8000)] * 300))
    assert len(o) == 300 and o[-1][1] == 1 and o[0][1] == 0
    g.run(pkt_cfg(list(range(7)), [0] * 7, 0, 1) + pkt_reset())
    a, _ = golay_pair(list(range(7)), [0] * 7)
    y = unpack(g.run(pkt_data([pack(0x1234, -0x777)]))[0][0])
    assert y == (int(a[-1].real) * 0x1234, int(a[-1].real) * -0x777), y
    y = [unpack(o[0]) for o in g.run(pkt_data([pack(0x7FFF, -0x8000)] * 300))]
    assert (0x7FFF, -0x8000) in y or (-0x8000, 0x7FFF) in y
    assert round_shift(3, 1) == 2 and round_shift(-3, 1) == -1 and round_shift(-1, 1) == 0

    # history persists across packets and config loads; RESET clears it
    x = [rand_word(rng) for _ in range(500)]
    g1, g2 = GolayModel(7), GolayModel(7)
    cfg = pkt_cfg(*rand_cfg(rng, 7), 9, 0)
    g1.run(cfg)
    g2.run(cfg)
    y1 = g1.run(pkt_data(x))
    y2 = g2.run(pkt_data(x[:123])) + g2.run(pkt_data(x[123:321])) + g2.run(pkt_data(x[321:]))
    assert [v[0] for v in y1] == [v[0] for v in y2]
    g1.run(pkt_cfg(*rand_cfg(rng, 7), 8, 2))
    assert g1.hist != GolayModel(7).hist
    g1.run(pkt_reset())
    assert g1.hist == GolayModel(7).hist and g1.rhist == GolayModel(7).rhist

    # framing and errors
    g = GolayModel(3)
    base = (g.p[:], g.w[:], g.shift, g.mode)
    g.run([(header(OP_LOAD_CFG, 1), 0), (cfg_word(0, 0), 0), (cfg_word(1, 0), 1)])
    assert g.err == ERR_CFG_LEN and (g.p, g.w, g.shift, g.mode) == base
    g.err = 0
    g.run([(header(OP_LOAD_CFG, 1), 0)] + [(cfg_word(0, 1), 0)] * 3 + [(5, 1)])
    assert g.err == ERR_CFG_LEN and (g.p, g.w, g.shift, g.mode) == base
    g.err = 0
    g.run(pkt_raw([header(OP_LOAD_CFG, 1), cfg_word(0, 0), cfg_word(3, 0), cfg_word(1, 0)]))
    assert g.err == ERR_CFG and (g.p, g.w, g.shift, g.mode) == base
    g.err = 0
    g.run(pkt_raw([header(OP_LOAD_CFG, 1), cfg_word(0, 0), cfg_word(1, 0, 0x40)]))
    assert g.err == ERR_CFG | ERR_CFG_LEN
    g.err = 0
    assert g.run(pkt_cfg([0, 1, 2], [0, 0, 0], 1, 3)) == [] and g.err == ERR_CFG
    g.err = 0
    g.run([(header(OP_LOAD_CFG, 1), 1)])
    assert g.err == ERR_CFG_LEN
    g.err = 0
    g.run(pkt_cfg([2, 2, 0], [1, 2, 3], 4, 2))
    assert g.err == 0 and g.p == [2, 2, 0] and g.w == [1, 2, 3] and g.shift == 4 and g.mode == 2
    g.run(pkt_raw([0x12345678, 1, 2]))
    assert g.err == ERR_HDR
    g.err = 0
    g.run(pkt_raw([header(OP_DATA, mode=1), 1]))
    assert g.err == ERR_HDR
    g.err = 0
    g.run(pkt_raw([header(OP_DATA, reserved=0x10), 1]))
    assert g.err == ERR_HDR
    g.err = 0
    g.run(pkt_raw([header(OP_DATA, reserved=0x2000), 1]))
    assert g.err == ERR_HDR
    g.err = 0
    g.run(pkt_reset([5, 6]))
    assert g.err == ERR_RST_LEN
    assert g.run(pkt_data([])) == []
    assert len(g.run(pkt_data([pack(1, 0)]))) == 1
    assert not header_valid(header(0))
    print("golay_model selftest PASS")


if __name__ == "__main__":
    _selftest()
