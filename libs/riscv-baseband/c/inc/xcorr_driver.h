#ifndef __XCORR_DRIVER_H__
#define __XCORR_DRIVER_H__

// Driver for the Q-engine Golay cross-correlator (golay_corr, Xilinx builds
// only), on top of the qstream transport (qstream.h):
//
//   VMEM -> DMA_3 -> stream_router -> golay_corr (port 1) -> stream_merge
//        -> DMA_4 -> VMEM
//
// golay_corr is a multiplier-free efficient Golay correlator (EGC) for a
// complementary pair (a, b) of length XCORR_L = 2^XCORR_M, defined by a
// stage config: a delay-exponent P(k) (a permutation of 0..M-1) and a seed
// w(k) in {+1,-1,+j,-j} per stage. Each output is one of
//   mode 0: Ra[n-L] + Rb[n]   (peak L*amp*2 when x = [a, b] back to back)
//   mode 1: Ra[n]             mode 2: Rb[n]
// rounded and saturated: sat16((v + round) >>> shift). History persists
// across packets and config loads; xcorr_reset() clears it.
// See doc/add-fir/PLAN.md, "Phase 2".
// Samples are complex Q1.15: I in [15:0], Q in [31:16].

#include "qstream.h"

#define XCORR_PORT                (1)
#define XCORR_M                   (7)
#define XCORR_L                   (1 << XCORR_M)
#define XCORR_DEFAULT_SHIFT       (XCORR_M)

#define XCORR_HDR_MAGIC           (0xC0A70000u)
#define XCORR_OP_DATA             (0x1)
#define XCORR_OP_LOAD_CFG         (0x2)
#define XCORR_OP_RESET            (0x3)
#define XCORR_HDR(op, shift, mode) (XCORR_HDR_MAGIC | ((((unsigned)(shift)) & 0x1fu) << 8) \
                                   | ((((unsigned)(mode)) & 0x3u) << 6) | ((unsigned)(op) & 0xfu))
#define XCORR_HDR_DATA            XCORR_HDR(XCORR_OP_DATA, 0, 0)
#define XCORR_HDR_RESET           XCORR_HDR(XCORR_OP_RESET, 0, 0)

#define XCORR_MODE_SUM            (0)   // Ra[n-L] + Rb[n]
#define XCORR_MODE_RA             (1)
#define XCORR_MODE_RB             (2)

#define XCORR_W_P1                (0)   // seed +1
#define XCORR_W_M1                (1)   // seed -1
#define XCORR_W_PJ                (2)   // seed +j
#define XCORR_W_MJ                (3)   // seed -j
#define XCORR_CFG_WORD(p, w)      (((((unsigned)(w)) & 0x3u) << 4) | ((unsigned)(p) & 0xfu))

#define XCORR_SAMPLE(i, q)        ((((unsigned)(q) & 0xffffu) << 16) | ((unsigned)(i) & 0xffffu))

#define XCORR_OK                  (0)
#define XCORR_EINVAL              (-1)

// Call once after qstream_init() and before any other xcorr_* call.
void xcorr_init(void);

// Load XCORR_M stage config words (XCORR_CFG_WORD) from VMEM with the output
// shift (0..31) and mode (0..2). Produces no output. The new config applies
// after all earlier samples have left the pipeline.
int xcorr_load_cfg(const unsigned int *vmem_cfg, unsigned int shift, unsigned int mode);

// Clear the correlator history (config is kept). Produces no output.
int xcorr_reset(void);

// Correlate n samples from `in` into `out` (both VMEM, n >= 1). History
// carries over between calls.
int xcorr_correlate(const unsigned int *in, unsigned int *out, unsigned int n);

// xcorr_correlate() that calls cb(XCORR_PORT, seq, out, n, ctx) from
// qstream_poll() once the output has landed.
int xcorr_correlate_cb(const unsigned int *in, unsigned int *out, unsigned int n,
                       qstream_cb_t cb, void *ctx);

// Send `n` raw words as one port-1 packet (the driver prepends the route
// word; the caller supplies the header). If the packet produces output,
// `out_n` words are received into `out`; use out_n = 0 otherwise.
int xcorr_send_raw(const unsigned int *vmem_words, unsigned int n,
                   unsigned int *out, unsigned int out_n);

// Write the Golay pair (a, b) generated by stage config p[k], w[k]
// (k = 0..XCORR_M-1) as packed samples scaled by amp (1..0x7fff) into
// a[0..XCORR_L-1] and b[0..XCORR_L-1]. p must be a permutation of
// 0..XCORR_M-1. Returns XCORR_OK or XCORR_EINVAL. Any memory works.
int xcorr_golay_pair_words(const unsigned char *p, const unsigned char *w,
                           unsigned int amp, unsigned int *a, unsigned int *b);

// The most recent merge tag received from the correlator port.
unsigned int xcorr_last_tag(void);

#endif /* __XCORR_DRIVER_H__ */
