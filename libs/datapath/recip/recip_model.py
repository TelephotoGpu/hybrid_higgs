#!/usr/bin/env python3
"""Bit-exact model of the FFT datapath reciprocal (doc/kernel/NOTES.md §12).

recip(x) is the per-cmul 1/c unit (libs/spinal qengine/Reciprocal.scala):
the d-engine algorithm (libs/d-engine/rtl/reciprocal) in Q6.10, so for a
16-bit lane value X the result is about 2^20 / X, with fixed edge cases:
sign-magnitude for X < 0, +-32767 when |X| < 32 (including X = 0).

cmul_lane() models one FFT-datapath lane for the "eq" configs (radix-4
bypassed): m2c operand muxes (code 3 = 1/c on m2c_ac and m2c_cd), muladdsub,
bs and round_sat. With the cdiv config word (cmul with ac = cd = 3) and
d = 0 the lane computes (a + jb) / c.

Commands:
  table <out>             recip() of all 65536 inputs, one hex per line
  check <got>             compare a table from the RTL unit test
  gen-header <out.h> <n>  test_recip_1 vmem vectors and expected output
"""
import random
import sys

M = 6
C1 = 0x5DD  # 1.466 in Q6.10
C2 = 0x401  # 1.0012 in Q6.10
SAT = 0x7FFF


def s16(v):
    v &= 0xFFFF
    return v - 0x10000 if v & 0x8000 else v


def lzc16(m):
    return 16 - m.bit_length()


def recip_mag(m):
    """1/m for 32 <= m <= 32768, Q6.10 (d-engine reciprocal.v datapath)."""
    lz = lzc16(m)
    xn = m >> (M - lz) if lz <= M else (m << (lz - M)) & 0xFFFF
    y0 = C1 - xn
    t = (xn * y0 >> 10) & 0xFFFF
    u = (C2 - t) & 0xFFFF
    r = (u * y0 >> 10) & 0xFFFF
    r = SAT if r >> 14 else (r << 2) & 0xFFFF
    r = r >> (M - lz) if lz <= M else (r << (lz - M)) & 0xFFFF
    return SAT if r & 0x8000 else r


def recip(x):
    """Signed 16-bit X -> signed result (fits 16 bits, sign-extended to 18)."""
    x = s16(x)
    m = -x if x < 0 else x
    r = SAT if m < 32 else recip_mag(m)
    return -r if x < 0 else r


def m2c(code, ins):
    """m2c with inputs ins by code (None or missing = constant 1)."""
    v = ins[code] if code < len(ins) else None
    return 1 if v is None else v


def bs_round_sat(v, cfg):
    """bs_dat_2_1 + round_sat_dat_1_1 on a signed 36-bit value."""
    sh = cfg & 0x3F
    u = v & ((1 << 36) - 1)
    sign = (u >> 35) & 1
    if cfg & 0x40 and sign:
        return 0
    if sh <= 19:
        top = u >> (15 + sh)
        pre_sat = not (top == 0 or top == (1 << (21 - sh)) - 1)
    else:
        pre_sat = False
    rnd = (u >> (sh - 1)) & 1 if 1 <= sh <= 35 else 0
    rounded = s16(u >> sh) + rnd
    if pre_sat or not -0x8000 <= rounded <= 0x7FFF:
        return -0x8000 if sign else 0x7FFF
    return rounded


def cmul_lane(a, b, c, d, cfg16, bs_re, bs_im):
    """One cmul lane: x = a + jb (k8), y = c + jd (k9), cfg16 = its k14 short."""
    f = [(cfg16 >> (2 * i)) & 3 for i in range(8)]
    rc = recip(c)
    ac = m2c(f[0], [a, c, None, rc])
    bc = m2c(f[1], [b, c])
    bd = m2c(f[2], [b, d])
    cb = m2c(f[3], [c, b])
    cd = m2c(f[4], [c, d, None, rc])
    da = m2c(f[5], [d, a])
    re = a * ac + bc * bd if f[6] & 1 else a * ac - bc * bd
    im = cb * cd + d * da if f[7] & 1 else cb * cd - d * da
    return bs_round_sat(re, bs_re), bs_round_sat(im, bs_im)


CDIV = 0x4753  # cmul 0x4451 with m2c_ac = m2c_cd = 3
CDIV_SHIFT = 5  # Q1.15 / Q1.15: a * (2^20 / c) >> 5 = 2^15 * a / c


def vectors(n, seed=1):
    """(a, b, c, d) per sample: all c ranges, d = 0 except the last quarter."""
    rng = random.Random(seed)
    special = [0, 1, -1, 31, -31, 32, -32, 33, 63, 64, 512, 1024, 32767,
               -32767, -32768, 16384, -16384, 1000, -1000, 100]
    out = []
    for i in range(n):
        a = rng.randint(-32768, 32767)
        b = rng.randint(-32768, 32767)
        if i < len(special):
            c = special[i]
        else:
            c = rng.choice([rng.randint(-32768, 32767), rng.randint(-64, 64),
                            rng.randint(-2048, 2048)])
        d = 0 if i < 3 * n // 4 else rng.randint(-32768, 32767)
        out.append((a, b, c, d))
    return out


def word(re, im):
    return ((im & 0xFFFF) << 16) | (re & 0xFFFF)


def gen_header(path, n):
    rows = []
    for a, b, c, d in vectors(n):
        re, im = cmul_lane(a, b, c, d, CDIV, CDIV_SHIFT, CDIV_SHIFT)
        rows.append((word(a, b), word(c, d), word(re, im)))
    with open(path, 'w') as f:
        f.write('// generated by libs/datapath/recip/recip_model.py gen-header\n')
        f.write('#ifndef RECIP_VECTORS_H\n#define RECIP_VECTORS_H\n')
        f.write('#include "vmem.h"\n#define RECIP_N %d\n' % n)
        # vmem rows: x and y feed vector_divide_1024 directly
        for k, name in enumerate(['recip_x', 'recip_y', 'recip_exp']):
            f.write('VMEM_SECTION unsigned int %s[RECIP_N] = {\n' % name)
            for i in range(0, n, 8):
                f.write('  ' + ', '.join('0x%08x' % r[k] for r in rows[i:i + 8]) + ',\n')
            f.write('};\n')
        f.write('#endif\n')


def main(argv):
    if len(argv) >= 2 and argv[0] == 'table':
        with open(argv[1], 'w') as f:
            for x in range(65536):
                f.write('%05x\n' % (recip(x) & 0x3FFFF))
    elif len(argv) >= 2 and argv[0] == 'check':
        got = [int(l, 16) for l in open(argv[1]) if l.strip()]
        bad = [(x, g) for x, g in enumerate(got) if g != recip(x) & 0x3FFFF]
        if len(got) != 65536 or bad:
            for x, g in bad[:10]:
                print('x=%04x got=%05x exp=%05x' % (x, g, recip(x) & 0x3FFFF))
            print('FAIL: %d results, %d mismatches' % (len(got), len(bad)))
            return 1
        print('PASS: all 65536 reciprocals bit-exact')
    elif len(argv) >= 3 and argv[0] == 'gen-header':
        gen_header(argv[1], int(argv[2]))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
