#!/usr/bin/env python3
"""Signal-name lock for the Spinal-generated piston netlists.

Waveform (.gtkw), TCL and LPF files, tb.cpp and the C headers refer to
hierarchical names inside piston.v; a generator change must not rename them
silently. This extracts every declared port / wire / reg / instance name
(minus Spinal temporaries _zz_*) and compares it with names.lock.

  names.py check FILE...   fail on any added or removed name
  names.py lock  FILE...   rewrite names.lock
"""
import argparse
import os
import re
import sys

DECL = re.compile(r'^[ \t]*(input|output|inout|wire|reg)\b\s*(?:wire|reg)?\s*(?:signed\s+)?(?:\[[^\]]+\]\s*)?(\w+)', re.M)
INST = re.compile(r'^[ \t]+(?:\w+|\))[ \t]+(\w+)[ \t]*\([ \t]*$', re.M)
KIND = {'input': 'port', 'output': 'port', 'inout': 'port', 'wire': 'wire', 'reg': 'reg'}


def names(path):
    src = open(path).read()
    base = os.path.basename(path)
    out = set()
    for kind, name in DECL.findall(src):
        if not name.startswith('_zz_'):
            out.add((base, KIND[kind], name))
    for name in INST.findall(src):
        out.add((base, 'inst', name))
    return out


def dedup(entries):
    """Signals Spinal suffixed to resolve a clash (wires/regs x and x_1)."""
    by_file = {}
    for f, k, n in entries:
        if k in ('wire', 'reg'):
            by_file.setdefault(f, set()).add(n)
    return sorted((f, n) for f, ns in by_file.items() for n in ns
                  if re.search(r'_[1-9]\d*$', n) and re.sub(r'_\d+$', '', n) in ns)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('mode', choices=['check', 'lock'])
    ap.add_argument('--lock', default=os.path.join(os.path.dirname(__file__), 'names.lock'))
    ap.add_argument('files', nargs='+')
    a = ap.parse_args()

    cur = set().union(*(names(f) for f in a.files))
    lines = sorted(' '.join(e) for e in cur)

    if a.mode == 'lock':
        with open(a.lock, 'w') as fh:
            fh.write('# generated by names.py lock; see doc/kernel/NOTES.md (name lock)\n')
            fh.write(''.join(l + '\n' for l in lines))
        print(f'names: locked {len(lines)} names in {a.lock}')
        return 0

    old = {l.strip() for l in open(a.lock) if l.strip() and not l.startswith('#')}
    new = set(lines)
    added, removed = sorted(new - old), sorted(old - new)
    bad = [(f, n) for f, n in dedup(cur) if f'{f} wire {n}' not in old and f'{f} reg {n}' not in old]
    for l in removed:
        print(f'- {l}')
    for l in added:
        print(f'+ {l}')
    for f, n in bad:
        print(f'! {f}: {n} looks like a Spinal name-clash suffix')
    if added or removed or bad:
        print(f'names: {len(removed)} removed, {len(added)} added, {len(bad)} clash '
              f'(rename, or accept with make names_lock and migrate saved paths)')
        return 1
    print(f'names: {len(lines)} names match {a.lock}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
